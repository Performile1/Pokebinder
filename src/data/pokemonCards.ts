export function searchPokemonCards(query: string, setFilter?: string): PokemonCard[] {
  let list = POKEMON_CARD_DATABASE;
  if (setFilter && setFilter !== 'ALL') {
    list = list.filter(c => c.setName.toLowerCase().includes(setFilter.toLowerCase()));
  }

  const q = query.trim().toLowerCase();
  if (!q) return list;

  const cleanQ = q.replace(/^0+/, '');

  return list.filter(card => {
    const cardNum = card.setNumber.split('/')[0].toLowerCase().replace(/^0+/, '');
    const fullSetNum = card.setNumber.toLowerCase();
    const nameMatch = card.name.toLowerCase().includes(q);
    const setMatch = card.setName.toLowerCase().includes(q);
    const numMatch = cardNum === cleanQ || fullSetNum.includes(q) || cleanQ === fullSetNum;
    const rarityMatch = card.rarity.toLowerCase().includes(q);
    return nameMatch || numMatch || setMatch || rarityMatch;
  });
}

export function findMatchingCard(queryName?: string, querySetNumber?: string): PokemonCard {
  if (querySetNumber) {
    const cleanNum = querySetNumber.trim().replace(/^0+/, '');
    const foundByNum = POKEMON_CARD_DATABASE.find(c => {
      const cardNum = c.setNumber.split('/')[0].replace(/^0+/, '');
      return cardNum === cleanNum || c.setNumber.toLowerCase() === querySetNumber.toLowerCase();
    });
    if (foundByNum) return foundByNum;
  }

  if (queryName) {
    const q = queryName.toLowerCase();
    const foundByName = POKEMON_CARD_DATABASE.find(c =>
      c.name.toLowerCase().includes(q) || q.includes(c.name.toLowerCase())
    );
    if (foundByName) return foundByName;
  }

  return POKEMON_CARD_DATABASE[0];
}
